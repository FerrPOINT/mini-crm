export function useUiLabels() {
  const { t, i18n } = useTranslation();
  const defaults = i18n?.language?.startsWith('en') ? messages.en : messages.ru;
  return Object.fromEntries(
    Object.entries(defaults).map(([key, value]) => [
      key,
      t(`baseUi.${key}`, { defaultValue: value }),
    ]),
  ) as Record<keyof typeof messages.ru, string>;
}
